"""Automated Well Incident Post-Mortem and Audit Exporter.

Generates structured Markdown and JSON incident dossiers when kick precursors,
swab underbalances, pack-offs, or washouts are flagged by the digital twin.
"""

from __future__ import annotations

from datetime import datetime, timezone
import json
from typing import Any, Dict, Optional
from pydantic import BaseModel

from rig_twin.core.models import (
    AnomalyDetectionResult,
    PhysicsBaseline,
    TelemetryRecord,
)
from rig_twin.physics.well_control_kill_sheet import (
    WellControlEngine,
    WellControlInput,
    KillSheetResult,
)


class IncidentReportExporter:
    """Builds auditable post-mortem reports detailing downhole anomalies and kill solutions."""

    @staticmethod
    def generate_report(
        anomaly: AnomalyDetectionResult,
        telemetry: TelemetryRecord,
        physics: PhysicsBaseline,
        kill_sheet: Optional[KillSheetResult] = None,
    ) -> Dict[str, Any]:
        """Generate both Markdown report string and JSON structured payload."""
        incident_id = f"INC-{anomaly.well_id}-{anomaly.timestamp.strftime('%Y%m%d-%H%M%S')}"

        # If kick precursor and kill sheet not provided, compute automated kill sheet
        if not kill_sheet and "KICK" in anomaly.classification.value:
            inputs = WellControlInput(
                well_id=anomaly.well_id,
                current_mud_weight_ppg=telemetry.mud_weight_in_ppg,
                true_vertical_depth_ft=telemetry.true_vertical_depth_ft,
                measured_depth_ft=telemetry.measured_depth_ft,
                shut_in_drillpipe_pressure_psi=max(abs(anomaly.spp_residual_psi), 250.0),
                shut_in_casing_pressure_psi=max(abs(anomaly.spp_residual_psi) + 180.0, 450.0),
                pit_gain_bbl=max(telemetry.pit_volume_total_bbl - 500.0, 12.0),
            )
            kill_sheet = WellControlEngine(inputs).generate_kill_sheet()

        ecd_res_str = f"{anomaly.ecd_residual_ppg:+.3f} ppg" if anomaly.ecd_residual_ppg is not None else "N/A"
        obs_ecd_val = telemetry.downhole_ecd_ppg if telemetry.downhole_ecd_ppg is not None else physics.dynamic_ecd_ppg

        # Build Markdown document
        md_lines = [
            f"# WELL INCIDENT AUDIT DOSSIER: {incident_id}",
            f"**Generated by Rig Digital Twin Core Autonomous System**",
            f"- **Timestamp:** {anomaly.timestamp.isoformat()}",
            f"- **Well ID:** `{anomaly.well_id}`",
            f"- **Measured Depth:** {anomaly.measured_depth_ft:.1f} ft (TVD: {telemetry.true_vertical_depth_ft:.1f} ft)",
            f"- **Classification:** **{anomaly.classification.value}** ({anomaly.severity.value})",
            f"- **Confidence Anomaly Score:** `{anomaly.anomaly_score:.2f} / 1.00`",
            "",
            "## 1. Executive Summary & Diagnostic",
            f"> **Diagnostic:** {anomaly.diagnostic_message}",
            "",
            f"**Detection Rule:** `{anomaly.detection_rule}`",
            f"**Recommended Immediate Action:** `{anomaly.recommended_action or 'Perform flow check'}`",
            "",
            "## 2. Telemetry vs Deterministic Physics Discrepancy",
            "| Parameter | Observed (Telemetry) | Theoretical Physics | Residual Delta |",
            "| :--- | :--- | :--- | :--- |",
            f"| **Standpipe Pressure** | {telemetry.standpipe_pressure_psi:.1f} psi | {physics.total_predicted_spp_psi:.1f} psi | **{anomaly.spp_residual_psi:+.1f} psi** |",
            f"| **Flow Rate (Out vs In)** | {telemetry.flow_rate_out_gpm:.1f} gpm (out) | {telemetry.flow_rate_in_gpm:.1f} gpm (in) | **{anomaly.flow_residual_gpm:+.1f} gpm** |",
            f"| **Dynamic ECD** | {obs_ecd_val:.2f} ppg | {physics.dynamic_ecd_ppg:.2f} ppg | **{ecd_res_str}** |",
            f"| **Pit Volume Rate of Change** | {telemetry.pit_rate_of_change_bbl_hr:.1f} bbl/hr | 0.0 bbl/hr | **{anomaly.pit_residual_bbl_min:+.2f} bbl/min** |",
            f"| **Tripping Velocity** | {telemetry.string_velocity_ft_min:.1f} ft/min | 0.0 ft/min | Swab Loss: {physics.swab_pressure_loss_psi:.1f} psi |",
            "",
        ]

        if kill_sheet:
            md_lines.extend([
                "## 3. Automated Well Control Kill Solution (API RP 59 / IADC)",
                f"- **Current Mud Weight:** {kill_sheet.current_mud_weight_ppg:.2f} ppg",
                f"- **Calculated Kill Mud Weight (KMW):** **{kill_sheet.kill_mud_weight_ppg:.2f} ppg**",
                f"- **Initial Circulating Pressure (ICP):** {kill_sheet.initial_circulating_pressure_psi:.1f} psi",
                f"- **Final Circulating Pressure (FCP):** {kill_sheet.final_circulating_pressure_psi:.1f} psi",
                f"- **Initial MAASP:** {kill_sheet.initial_maasp_psi:.1f} psi",
                f"- **Estimated Influx Fluid:** {kill_sheet.influx_type_estimate} ({kill_sheet.influx_gradient_psi_ft:.3f} psi/ft)",
                f"- **Strokes Surface to Bit:** {kill_sheet.surface_to_bit_strokes} strokes",
                f"- **Total Circulation Strokes:** {kill_sheet.total_well_strokes} strokes",
                "",
                "### Drillpipe Pressure Step-Down Schedule",
                "| Strokes | Kill Mud Progress | Drillpipe Pressure (psi) |",
                "| :--- | :--- | :--- |",
            ])
            for step in kill_sheet.step_down_schedule:
                md_lines.append(f"| {step['strokes']} | {step['kill_mud_progress_pct']:.0f}% | {step['drillpipe_pressure_psi']:.1f} |")

        md_lines.extend([
            "",
            "## 4. Driller Verification Checklist",
            "- [ ] Space out tool joint above rotary table / BOP",
            "- [ ] Shut down mud pumps and observe standpipe / casing pressures",
            "- [ ] Verify flow paddle / flow sensor for positive returns",
            "- [ ] Verify pit level gain on active tanks",
            "- [ ] If flow confirmed, close annular preventer or upper pipe rams",
            "- [ ] Record stabilized SIDPP and SICP",
            "",
            "---",
            f"*Report generated automatically by Rig Digital Twin Core at {datetime.now(timezone.utc).strftime('%Y-%m-%d %H:%M:%S UTC')}*",
        ])

        markdown_text = "\n".join(md_lines)
        json_payload = {
            "incident_id": incident_id,
            "generated_at": datetime.now(timezone.utc).isoformat(),
            "anomaly": anomaly.model_dump(mode="json"),
            "telemetry_snapshot": telemetry.model_dump(mode="json"),
            "physics_baseline": physics.model_dump(mode="json"),
            "kill_sheet": kill_sheet.model_dump(mode="json") if kill_sheet else None,
        }

        return {
            "incident_id": incident_id,
            "markdown": markdown_text,
            "payload": json_payload,
        }
